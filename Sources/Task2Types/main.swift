// Завдання №2: Робота з типами

// 1. Ціле десяткове 12 з мінімальною розрядною сіткою (невід'ємне -> UInt8, 8 біт)
let a: UInt8 = 12

// 2. Ціле десяткове -100 з мінімальною розрядною сіткою (зі знаком -> Int8, 8 біт)
let b: Int8 = -100

// 3. Шістнадцяткове ціле, що дорівнює десятковому 128
let c = 0x80

// 4. Мінімальне значення у межах 16-розрядної сітки
let d = Int16.min          // -32768

// 5. Максимальне значення у межах 64-розрядної сітки
let e = Int64.max          // 9223372036854775807 (для беззнакового: UInt64.max)

// 6. Число з плаваючою крапкою 10235.34 з мінімальною розрядною сіткою (Float, 32 біти)
let f: Float = 10235.34

// 7. Символ "a"
let g: Character = "a"

// 8. Рядок "Hello World"
let h: String = "Hello World"

// 9. Істина
let i: Bool = true

// 10. Число 12 та його рядкове представлення "twelve" (кортеж)
let j: (number: Int, name: String) = (12, "twelve")

print("1.  \(a)  (\(type(of: a)))")
print("2.  \(b)  (\(type(of: b)))")
print("3.  \(c) = 0x\(String(c, radix: 16))  (\(type(of: c)))")
print("4.  \(d)  (\(type(of: d)))")
print("5.  \(e)  (\(type(of: e)))")
print("6.  \(f)  (\(type(of: f)))")
print("7.  \(g)  (\(type(of: g)))")
print("8.  \(h)  (\(type(of: h)))")
print("9.  \(i)  (\(type(of: i)))")
print("10. \(j)  (\(type(of: j)))")
